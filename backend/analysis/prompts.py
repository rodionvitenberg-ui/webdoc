def resolve_language(language_code: str) -> str:
    """Приводит 'ru-RU'/'EN' к поддерживаемому коду; неизвестный — 'en'."""
    code = (language_code or "ru").split("-")[0].lower()
    return code if code in RESULT_FALLBACKS else "en"


